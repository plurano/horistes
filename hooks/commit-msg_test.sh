# Cases for commit-msg.sh: each message with the verdict the policy must give.
# Usage: sh .config/hooks/commit-msg_test.sh [path-to-the-hook]
# The attribution lines below are test data, not attribution of this file.
set -eu

hook="${1:-$(dirname "$0")/commit-msg.sh}"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
ran=0
failed=0

dco='Signed-off-by: Ada Example <ada@example.org>'
tool='names a model or coding tool'
subject72="fix: $(printf '%072d' 0)"
subject73="fix: $(printf '%073d' 0)"

# check <0|1> <name> <fragment of the refusal, or -> <message line>...
# 0 = the hook accepts the message, 1 = it refuses it. Any other exit status of the hook is
# an error of the hook itself and fails the case.
check() {
  want="$1" name="$2" fragment="$3"
  shift 3
  printf '%s\n' "$@" > "$work/msg"
  ran=$((ran + 1))
  got=0
  sh "$hook" "$work/msg" > "$work/out" 2>&1 || got=$?
  if [ "$got" != "$want" ]; then
    failed=$((failed + 1))
    echo "FAIL $name: exit $got, want $want" >&2
    sed -e 's/^/  | /' "$work/out" >&2
    return 0
  fi
  if [ "$fragment" != - ] && ! grep -Fq -- "$fragment" "$work/out"; then
    failed=$((failed + 1))
    echo "FAIL $name: the refusal does not say '$fragment'" >&2
    sed -e 's/^/  | /' "$work/out" >&2
  fi
}

# Accepted.
check 0 'plain message' - 'feat(api): add a thing' '' 'Body.' '' "$dco"
check 0 'subject of 72 characters' - "$subject72" '' "$dco"
check 0 'a person as co-author' - 'fix: a thing' '' 'Co-authored-by: Grace Example <grace@example.org>' "$dco"
check 0 'a person whose first name is Claude' - 'fix: a thing' '' 'Co-authored-by: Claude Dupont <claude.dupont@example.org>' "$dco"
check 0 'a name that only contains a tool name' - 'fix: a thing' '' 'Co-authored-by: Raider Example <raider@example.org>' "$dco"
check 0 'products named in prose' - 'chore: select the clients' '' 'The Codex and Claude Code folders are selected; Copilot is not.' '' "$dco"
check 0 'generated code named in prose' - 'build: regenerate' '' 'The server is generated with ogen and the queries by sqlc.' '' "$dco"
check 0 'a trailer in a comment line' - 'fix: a thing' '' '# Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>' "$dco"

# Refused: the existing policy.
check 1 'subject of 73 characters' 'Conventional Commit' "$subject73" '' "$dco"
check 1 'subject without a type' 'Conventional Commit' 'add a thing' '' "$dco"
check 1 'no sign-off' 'missing DCO trailer' 'fix: a thing' '' 'Body.'

# Refused: a trailer or footer that names a model or coding tool.
check 1 'model as co-author' "$tool" 'fix: a thing' '' 'Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>' "$dco"
check 1 'model as co-author, lower case' "$tool" 'fix: a thing' '' 'co-authored-by: claude sonnet <claude@example.org>' "$dco"
check 1 'vendor address only' "$tool" 'fix: a thing' '' 'Co-authored-by: Assistant <noreply@anthropic.com>' "$dco"
check 1 'tool as co-author' "$tool" 'fix: a thing' '' 'Co-authored-by: Copilot <223556219+Copilot@users.noreply.github.com>' "$dco"
check 1 'no space after the colon' "$tool" 'fix: a thing' '' 'Co-authored-by:Codex <codex@openai.com>' "$dco"
check 1 'indented trailer' "$tool" 'fix: a thing' '' '  Co-authored-by: Gemini <gemini@example.org>' "$dco"
check 1 'a person and a tool' "$tool" 'fix: a thing' '' 'Co-authored-by: Grace Example <grace@example.org>' 'Co-authored-by: Cursor <cursoragent@cursor.com>' "$dco"
check 1 'assisted-by trailer' "$tool" 'fix: a thing' '' 'Assisted-by: aider' "$dco"
check 1 'generated-by trailer' "$tool" 'fix: a thing' '' 'Generated-by: ChatGPT' "$dco"
check 1 'generated-with footer' "$tool" 'fix: a thing' '' '🤖 Generated with [Claude Code](https://claude.com/claude-code)' '' "$dco"
check 1 'generated-by footer, bare model name' "$tool" 'fix: a thing' '' 'Generated by Claude' '' "$dco"

if [ "$failed" != 0 ]; then
  echo "commit-msg_test: $failed of $ran cases failed" >&2
  exit 1
fi
echo "commit-msg_test: $ran cases passed"
